#!/usr/bin/env node
// Writes the nginx header snippets from src/shared/config (single CSP source):
//   docker/nginx/security-headers.conf     the app (csp.ts)
//   docker/nginx/page-runner-headers.conf  the interactive page runner (page-runner.ts, ADR 0023)
//   node scripts/generate-nginx-headers.mjs          → write the files
//   node scripts/generate-nginx-headers.mjs --check  → exit 1 if a file is out of date
// CSP_BACKEND_ORIGIN=https://<project>.supabase.co adds the live backend origin.
import { readFileSync, writeFileSync } from 'node:fs'

import { buildCsp, PERMISSIONS_POLICY, REFERRER_POLICY } from '../src/shared/config/csp.ts'
import { buildPageRunnerCsp } from '../src/shared/config/page-runner.ts'

const TARGET = 'docker/nginx/security-headers.conf'
const RUNNER_TARGET = 'docker/nginx/page-runner-headers.conf'

export function renderNginxHeaders(backendOrigin = process.env.CSP_BACKEND_ORIGIN || null) {
  const csp = buildCsp({ delivery: 'header', backendOrigin })
  return `# Generated by scripts/generate-nginx-headers.mjs from src/shared/config/csp.ts — do not edit.
# Included in every location that sets its own headers (nginx does not inherit add_header).
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "DENY" always;
add_header Referrer-Policy "${REFERRER_POLICY}" always;
add_header Permissions-Policy "${PERMISSIONS_POLICY}" always;
add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;
add_header Content-Security-Policy "${csp}" always;
`
}

/** The runner is framed by the app (same origin only) and keeps the network closed. */
export function renderPageRunnerHeaders() {
  return `# Generated by scripts/generate-nginx-headers.mjs from src/shared/config/page-runner.ts — do not edit.
# Only for /page-runner.html: the app frames it, so SAMEORIGIN instead of DENY.
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "SAMEORIGIN" always;
add_header Referrer-Policy "no-referrer" always;
add_header Permissions-Policy "${PERMISSIONS_POLICY.replace('camera=(self)', 'camera=()')}" always;
add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;
add_header Content-Security-Policy "${buildPageRunnerCsp('header')}" always;
add_header Cache-Control "no-cache" always;
`
}

const files = [
  [TARGET, renderNginxHeaders()],
  [RUNNER_TARGET, renderPageRunnerHeaders()],
]
if (process.argv.includes('--check')) {
  let stale = false
  for (const [target, expected] of files) {
    if (readFileSync(target, 'utf8') !== expected) {
      console.error(`✖ ${target} is out of date — run: npm run csp:nginx`)
      stale = true
    } else console.log(`✔ ${target} matches its source`)
  }
  if (stale) process.exit(1)
} else {
  for (const [target, expected] of files) {
    writeFileSync(target, expected)
    console.log(`✔ wrote ${target}`)
  }
}
