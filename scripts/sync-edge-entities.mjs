#!/usr/bin/env node
// Copies the pure domain model (src/entities, Zod + relative .ts imports only) into the Edge
// Functions, so they validate kits and AI output with exactly the app's rules (ADR 0018, 0021).
//   node scripts/sync-edge-entities.mjs          write the copy
//   node scripts/sync-edge-entities.mjs --check  fail if the copy is out of date (CI)
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = path.join(ROOT, 'src', 'entities')
const TARGET = path.join(ROOT, 'supabase', 'functions', '_shared', 'entities')
const HEADER =
  '// GENERATED by scripts/sync-edge-entities.mjs from src/entities — do not edit here.\n'

function sourceFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name)
    if (statSync(full).isDirectory()) return sourceFiles(full)
    return name.endsWith('.ts') && !name.endsWith('.test.ts') ? [full] : []
  })
}

function targetFiles(dir) {
  try {
    return readdirSync(dir).flatMap((name) => {
      const full = path.join(dir, name)
      return statSync(full).isDirectory() ? targetFiles(full) : [full]
    })
  } catch {
    return []
  }
}

const expected = new Map(
  sourceFiles(SOURCE).map((file) => [
    path.join(TARGET, path.relative(SOURCE, file)),
    HEADER + readFileSync(file, 'utf8'),
  ]),
)

if (process.argv.includes('--check')) {
  const stale = [
    ...[...expected].filter(([file, content]) => {
      try {
        return readFileSync(file, 'utf8') !== content
      } catch {
        return true
      }
    }),
    ...targetFiles(TARGET)
      .filter((file) => !expected.has(file))
      .map((file) => [file]),
  ].map(([file]) => path.relative(ROOT, file))
  if (stale.length > 0) {
    console.error(
      `Edge Function copy of src/entities is out of date (${stale.length} files). Run: npm run sync:edge`,
    )
    for (const file of stale) console.error(`  ${file}`)
    process.exit(1)
  }
  console.log('✔ Edge Function entities are in sync')
} else {
  rmSync(TARGET, { recursive: true, force: true })
  for (const [file, content] of expected) {
    mkdirSync(path.dirname(file), { recursive: true })
    writeFileSync(file, content)
  }
  console.log(`✔ Copied ${expected.size} files to ${path.relative(ROOT, TARGET)}`)
}
